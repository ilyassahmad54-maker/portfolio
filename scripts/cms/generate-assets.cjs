// Explicitly version the deployable assets that Phase 2 may reference.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { loadModule } = require('./load-module.cjs');
const data = JSON.parse(fs.readFileSync('data.json', 'utf8'));
loadModule('lib/cms/validation.ts').validatePortfolio(data);
const references = [...new Set([data.profile.profileImage, ...data.projects.map(p => p.image), data.profile.cvUrl])].sort();
const publicRoot = fs.realpathSync('public');
const assets = references.map(reference => {
  if (!reference.startsWith('/assets/') && reference !== '/cv.pdf') throw new Error('Expected local baseline asset');
  const file = fs.realpathSync(`public${reference}`);
  if (!file.startsWith(publicRoot + path.sep) || !fs.statSync(file).isFile()) throw new Error('Invalid baseline asset');
  const bytes = fs.readFileSync(file);
  return { path: reference, sha256: crypto.createHash('sha256').update(bytes).digest('hex'), bytes: bytes.length };
});
const manifest = JSON.stringify(assets, null, 2) + '\n';
const sql = `-- Generated by scripts/cms/generate-assets.cjs; immutable deployment baseline.
BEGIN;
SET LOCAL ROLE portfolio_cms_owner;
CREATE TABLE cms.legacy_assets (
  path text PRIMARY KEY,
  sha256 text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  byte_size bigint NOT NULL CHECK (byte_size > 0)
);
INSERT INTO cms.legacy_assets(path, sha256, byte_size) VALUES
${assets.map(a => `('${a.path}', '${a.sha256}', ${a.bytes})`).join(',\n')};
ALTER TABLE cms.legacy_assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE cms.legacy_assets FORCE ROW LEVEL SECURITY;
CREATE POLICY owner_only ON cms.legacy_assets TO portfolio_cms_owner USING (true) WITH CHECK (true);
CREATE TRIGGER immutable_legacy_assets BEFORE UPDATE OR DELETE OR TRUNCATE ON cms.legacy_assets
FOR EACH STATEMENT EXECUTE FUNCTION cms.reject_revision_mutation();
REVOKE ALL ON cms.legacy_assets FROM PUBLIC, portfolio_cms_runtime, portfolio_cms_seed;
COMMIT;
`;
for (const [target, expected] of [['lib/cms/legacy-assets.json', manifest], ['supabase/migrations/202610120004_legacy_assets.sql', sql]]) {
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== expected) throw new Error('Asset baseline drift: review a new asset migration before building');
  } else fs.writeFileSync(target, expected);
}
