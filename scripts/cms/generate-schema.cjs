const fs = require('node:fs');
const schema = fs.readFileSync('lib/cms/portfolio.schema.json', 'utf8').trim();
const sql = `-- Generated by node scripts/cms/generate-schema.cjs. Do not edit by hand.
BEGIN;
SET LOCAL ROLE portfolio_cms_owner;
CREATE FUNCTION cms.content_schema() RETURNS jsonb
LANGUAGE sql IMMUTABLE SET search_path = pg_catalog, pg_temp AS $function$
  SELECT $schema$${schema}$schema$::jsonb;
$function$;
COMMIT;
`;
const target = 'supabase/migrations/202610120002_content_schema.sql';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== sql) throw new Error('SQL schema is stale; run npm run cms:schema');
} else fs.writeFileSync(target, sql);
